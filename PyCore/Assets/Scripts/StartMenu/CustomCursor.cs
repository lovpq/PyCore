using UnityEngine;

/// <summary>
/// устанавливает пользовательский курсор мыши для игры
/// 
/// что делает этот скрипт:
/// - Заменяет стандартный курсор Windows на свой (из текстуры)
/// - Устанавливает курсор при запуске игры
/// - Восстанавливает стандартный курсор при выходе
/// 
/// как использовать в unity:
/// 1. Добавьте этот скрипт на любой GameObject в сцене (например, на Camera)
/// 2. Назначьте текстуру курсора в Inspector (формат PNG или JPG)
/// 3. Настройте hotSpot (точку клика на курсоре)
/// 
/// как работает:
/// - Cursor.SetCursor() меняет курсор системы
/// - hotSpot определяет, какая точка курсора является "кликабельной"
/// - OnDestroy() восстанавливает стандартный курсор
/// </summary>
public class CustomCursor : MonoBehaviour
{
    // текстура для курсора (изображение курсора)
    // должна быть Import Settings -> Texture Type: Cursor
    public Texture2D cursorTexture;
    
    // точка "клика" на курсоре
    // (0,0) = левый верхний угол, обычно для стрелки
    // для курсора-перекрестия может быть (16, 16) - центр
    public Vector2 hotSpot = Vector2.zero;

    /// <summary>
    /// вызывается Unity при запуске скрипта
    /// устанавливает пользовательский курсор
    /// </summary>
    void Start()
    {
        // если текстура курсора назначена в Inspector
        if (cursorTexture != null)
            // устанавливаем кастомный курсор
            // CursorMode.Auto автоматически выбирает режим отображения
            Cursor.SetCursor(cursorTexture, hotSpot, CursorMode.Auto);
    }

    /// <summary>
    /// вызывается Unity при уничтожении объекта
    /// восстанавливает стандартный курсор Windows
    /// </summary>
    void OnDestroy()
    {
        // восстанавливаем стандартный курсор
        // null = использовать стандартный курсор системы
        Cursor.SetCursor(null, Vector2.zero, CursorMode.Auto);
    }
}